"""``make results`` -- the baselines table, rebuilt from the cards.

The table refuses to mix splits and warns on mixed commits, because rows that
came from different code or different data are not comparable and the whole
point of a results table is comparison.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

RESULTS = Path("evaluation/results")
DESTINATION = Path("docs/results.md")

# Increasing order of what the model knows, which is the order the story is told
# in: a ruler, then a model that ignores time, then one that does not.
_FAMILY_ORDER = {"random": 0, "popularity": 1, "decayed_popularity": 2}


def load_cards(directory: Path) -> list[dict[str, Any]]:
    """Read every card in a directory, newest schema assumed.

    Args:
        directory: Where ``run_eval`` and ``run_eval_sweep`` write.

    Returns:
        Cards sorted by family, then by half-life within a family.

    Raises:
        FileNotFoundError: If the directory holds no cards. An empty table is
            worse than no table: it reads as "the baselines lost".
    """
    cards = [json.loads(path.read_text()) for path in sorted(directory.glob("*.json"))]
    if not cards:
        raise FileNotFoundError(f"no report cards in {directory}; run `make eval` first")

    def key(card: dict[str, Any]) -> tuple[int, float]:
        family = _FAMILY_ORDER.get(card["model"], len(_FAMILY_ORDER))
        return family, float(card.get("half_life_days") or 0.0)

    return sorted(cards, key=key)


def _label(card: dict[str, Any]) -> str:
    """Row label, carrying the half-life when there is one."""
    half_life = card.get("half_life_days")
    if half_life is None:
        return str(card["model"])
    return f"{card['model']} (hl={half_life:g}d)"


def _row(card: dict[str, Any]) -> str:
    overall = card["cohorts"]["overall"]
    cold = card["cohorts"]["cold_item"]
    cold_user = card["cohorts"]["cold_user"]
    low, high = overall["ci95"]
    # Older cards predate the ceiling; render them as unknown rather than
    # inventing 1.0, which would read as "this model had full room".
    ceiling = overall.get("gauc_ceiling")
    ceiling_cell = f"{ceiling:.4f}" if ceiling is not None else "—"
    coverage = overall.get("coverage@10")
    coverage_cell = f"{coverage:.4f}" if coverage is not None else "—"
    return (
        f"| {_label(card)} | {overall['gauc']:.4f} | {ceiling_cell} | "
        f"{overall['ndcg@10']:.4f} | [{low:.4f}, {high:.4f}] | {overall['mrr']:.4f} | "
        f"{overall['recall@10']:.4f} | {cold_user['gauc']:.4f} | {cold['gauc']:.4f} "
        f"| {coverage_cell} |"
    )


def render(cards: Sequence[dict[str, Any]]) -> str:
    """Render the table and the provenance that makes it quotable.

    Args:
        cards: Cards in display order.

    Returns:
        Markdown.

    Raises:
        ValueError: If the cards span more than one split or more than one ``k``.
            Stacking dev rows against test rows in one table is the exact error a
            results table exists to prevent, so it is refused rather than noted.
    """
    splits = {card["split"] for card in cards}
    if len(splits) > 1:
        raise ValueError(f"cards span multiple splits {sorted(splits)}; one table, one split")

    ks = {card["k"] for card in cards}
    if len(ks) > 1:
        raise ValueError(
            f"cards span multiple cutoffs k={sorted(ks)}; @10 and @20 are not one column"
        )

    split, k = splits.pop(), ks.pop()
    impressions = {card["cohorts"]["overall"]["impressions"] for card in cards}
    shas = sorted({card.get("git_sha", "unknown") for card in cards})

    lines = [
        "# Results",
        "",
        "<!-- Generated by `make results`. Do not edit: regenerate. -->",
        "",
        f"Split `{split}`, ranking within the impression, k={k}.",
        "",
        "| model | GAUC | ceiling | NDCG@10 | NDCG@10 95% CI | MRR | Recall@10 "
        "| cold-user GAUC | cold-item GAUC | coverage@10 |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += [_row(card) for card in cards]
    lines += [
        "",
        "## Reading this table",
        "",
        "**Every row here is a RANKING measurement, not a retrieval one.** Each model",
        "was asked to reorder the ~37 items MSN already chose to show, so every number",
        "is conditional on someone else's shortlist. None of these models has been",
        "asked to find candidates in the 65,238-item catalogue, and nothing here says",
        "whether it could. In particular `recall@10` is WITHIN-SLATE recall -- did the",
        "clicked item reach the top ten of the items shown -- and is not comparable to",
        "a retrieval Recall@10 over the full catalogue, which would be far smaller.",
        "The models live under `models/retrieval/` because they are candidate",
        "generators by nature; `evaluate_retrieval` exists and has not yet been run",
        "against any of them.",
        "",
        "**GAUC is the headline, not AUC.** Ranking only ever happens inside one",
        "impression, so a global AUC scores comparisons the system is never asked to",
        "make. Random sits at 0.5 by construction; that is the ruler being checked,",
        "not a model competing.",
        "",
        "**The CI resamples users, never impressions.** One user contributes many",
        "impressions and they are correlated, so an interval over impressions is",
        "narrower than the evidence supports. The cards carry that narrower interval",
        "too, under a key named so it cannot be quoted by accident.",
        "",
        "**The CI does not bracket the NDCG column, and should not.** The point",
        "estimate is a mean over impressions; the interval is over per-user means,",
        "which weights a user with one impression the same as a user with forty.",
        "They are two different estimands and the gap between them is the weighting,",
        "not noise.",
        "",
        "**`ceiling` is the most a perfect ranker could have scored.** A slate whose",
        "scores are all equal contributes exactly 0.5 to GAUC whatever those scores",
        "are, so a model that cannot discriminate within most slates is capped far",
        "below 1.0 before it ranks anything. A GAUC near 0.50 next to a ceiling near",
        "0.56 is a model that could barely see, not one that ranked badly; the cards",
        "carry `headroom_used` for the exact share. A dash means the card predates",
        "this field.",
        "",
        "**`coverage@10` is the share of the FULL catalogue a model ever puts in a",
        "slate's top ten.** Accuracy metrics cannot see the difference between a model",
        "that serves the whole catalogue well and one that serves the same few popular",
        "items to everyone, and on a news corpus the second is the easy way to a good",
        "NDCG. The denominator is the whole item map, not the items dev happened to",
        "show, so the number is small by construction and comparable across models.",
        "",
        "**Coverage only means something next to the ceiling.** A model that ties",
        "most slates has its ties resolved by row order, which scatters items across",
        "top-tens more evenly than any deliberate choice would -- so random posts the",
        "highest coverage in this table while choosing nothing at all. Read a high",
        "coverage as breadth only when the ceiling shows the model could discriminate.",
        "",
        "**Two cold cohorts, and they answer different questions.** cold-user GAUC is",
        "a user absent from train -- 88% of this split, so it tracks the headline",
        "closely. cold-item GAUC is a slate whose CLICKED item was absent from train,",
        "which is where the interaction-based baselines structurally fail.",
        "",
        "**cold-item GAUC is here because it is where the baselines break.** An item",
        "unseen in train has no popularity to score, so these models rank it by a",
        "constant. Any model that claims to beat them has to beat them *there*.",
        "",
        "## Provenance",
        "",
        f"- {len(cards)} cards from `{RESULTS}/`",
        f"- {', '.join(f'{n:,}' for n in sorted(impressions))} impressions",
        f"- commit: {', '.join(shas)}",
    ]

    if len(shas) > 1:
        lines += [
            "",
            "> **WARNING: these rows were produced by different commits.** They are",
            "> not strictly comparable. Re-run the whole suite on one commit before",
            "> quoting any difference between them.",
        ]

    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=RESULTS)
    parser.add_argument("--out", type=Path, default=DESTINATION)
    args = parser.parse_args(argv)

    cards = load_cards(args.results)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(cards))

    print(f"wrote {args.out} from {len(cards)} cards")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
