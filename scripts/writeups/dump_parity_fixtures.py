def seen_cases() -> list[dict[str, Any]]:
    """Bit positions for the seen-list filter.

    **The fourth parity surface.** The filter is written by one process and
    read by another, in different languages: if they disagree about which bits
    an item owns, the reader answers plausibly and wrongly in BOTH directions
    -- hiding fresh items and, worse, re-showing seen ones, which is the
    failure the one-sided guarantee exists to make impossible.

    ⚠️ **The arithmetic overflows in every language except this one.**
    ``_positions`` computes ``(base + index * step) % bits`` where ``base`` and
    ``step`` are both full 64-bit values read out of a blake2b digest. Python
    integers are arbitrary precision, so that sum is exact. A port holding them
    in a uint64 wraps at 2**64 first, and ``(x mod 2**64) mod bits`` is not
    ``x mod bits`` unless ``bits`` is a power of two -- which the sizing
    formula never produces. The cases below are chosen so the sum exceeds
    2**64 for the later hash positions, which is where a wrapping port
    diverges and a small-number test would not notice.
    """
    from models.reranking.seen import BloomFilter, sizing

    shapes = [
        # capacity, rate: the sizing we measured and shipped.
        (200, 0.01),
        # A tiny filter, where every position collides into a narrow range.
        (10, 0.1),
        # A wide one, so `bits` is large enough that the modulus matters.
        (5000, 0.001),
    ]

    cases: list[dict[str, Any]] = []
    for capacity, rate in shapes:
        bits, hashes = sizing(capacity, rate)
        filter_ = BloomFilter(bits=bits, hashes=hashes)
        # Item ids spanning the catalogue, plus 1 and a large value: the digest
        # is over the 8-byte big-endian id, so a port that used a different
        # width or byte order agrees on none of these.
        items = [1, 2, 7, 42, 65_238, 160_000, 2_147_483_647]
        cases.append(
            {
                "name": f"capacity {capacity} at {rate}",
                "capacity": capacity,
                "false_positive_rate": rate,
                "bits": bits,
                "hashes": hashes,
                "items": items,
                "expected_positions": [filter_._positions(item).tolist() for item in items],
            }
        )
    return cases


def search_cases() -> list[dict[str, Any]]:
    """Exact top-k: FAISS's IndexFlatIP against the Go in-process scan.

    **The sixth parity surface**, and its scope needs stating precisely because
    it is easy to claim more than it delivers.

    ADR 0013's rung 1 is HNSW, which is APPROXIMATE -- we measured it
    agreeing with exact search on 0.9866 of candidates -- so rung 2 cannot and
    should not reproduce rung 1 slate for slate. What IS checkable, and what
    actually matters, is that the Go scan computes the same EXACT answer FAISS
    computes: same scores, same ordering, same off-by-one on the item shift.
    Given that, the rung-1-to-rung-2 difference is exactly the
    approximate-vs-exact gap already measured, rather than an unknown
    quantity on top of it.

    The cases target where the two could diverge:

    - **exact ties**, where the tie-break rule decides the slate. This case
      found something better than a bug: **FAISS has no single tie order.**
      On two identical rows it keeps the earlier at ``k=1`` and the later at
      ``k=5`` and ``k=100``, because the ``k=1`` path and the heap path are
      different code. So the Go side keeps one consistent rule (numpy's first
      maximum, matching the re-ranker) and the Go test compares tied groups as
      SETS rather than chasing an order that is not stable to chase;
    - **k larger than the table**, where one may pad and the other truncate;
    - **negative scores**, since an implementation initialising its running
      best to zero passes every non-negative test.
    """
    import faiss

    rng = np.random.default_rng(11)

    def unit(rows: int, dim: int) -> np.ndarray:
        raw = rng.normal(size=(rows, dim)).astype("float32")
        # Bound and annotated rather than returned inline: np.linalg.norm is
        # typed as returning Any, so the division widens and strict mypy
        # rejects the implicit Any return.
        normalised: np.ndarray = raw / np.linalg.norm(raw, axis=1, keepdims=True)
        return normalised

    # Every row confined to the +x half-space, so a query at the -x pole scores
    # NEGATIVE against all of them.
    #
    # ⚠️ The obvious construction -- random rows, then query with the negation
    # of a random unit vector -- does not do this, and the first version of
    # this fixture got it wrong. Sixty-four random rows in eight dimensions
    # cover the sphere, so some row has a positive dot product with ANY
    # direction, and the best score stays positive. The negative path then goes
    # untested while looking tested. The guard test in the Go package is what
    # caught it.
    vectors = unit(64, 8)
    vectors[:, 0] = np.abs(vectors[:, 0]) + 1.0
    vectors /= np.linalg.norm(vectors, axis=1, keepdims=True)

    # Rows 5 and 6 made identical, so any query scores them equally and the
    # tie-break rule alone decides which is served.
    vectors[6] = vectors[5]

    away = np.zeros((1, 8), dtype="float32")
    away[0, 0] = -1.0

    queries = np.vstack(
        [
            unit(3, 8),
            # A query pointing straight at the duplicated pair.
            vectors[5:6],
            # The -x pole: every row has a positive first coordinate, so every
            # score here is negative. An implementation seeding its running best at
            # zero returns nothing for this query and passes every other case.
            away,
        ]
    ).astype("float32")

    index = faiss.IndexFlatIP(vectors.shape[1])
    index.add(vectors)

    cases: list[dict[str, Any]] = []
    for k in (1, 5, 100):
        scores, positions = index.search(queries, k)
        cases.append(
            {
                "name": f"exact top-{k}",
                "k": k,
                "dim": int(vectors.shape[1]),
                "vectors": vectors.tolist(),
                "queries": queries.tolist(),
                # Position p holds item p + 1; FAISS returns -1 when it finds
                # fewer than k, which becomes 0.
                "expected_items": to_item_ids(positions).tolist(),
                "expected_scores": scores.tolist(),
            }
        )
    return cases


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)

    for name, cases in (
        ("blend_cases.json", blend_cases()),
        ("rerank_cases.json", rerank_cases()),
        ("feature_cases.json", feature_cases()),
        ("seen_cases.json", seen_cases()),
        ("search_cases.json", search_cases()),
    ):
        path = OUT / name
        # sort_keys so a regeneration produces a reviewable diff rather than a
        # reordering, and a trailing newline so the file is POSIX-clean.
        #
        # ⚠️ Because keys ARE sorted, nothing in these files may depend on the
        # order of an object's keys. Anything ordered is an array. See
        # `blend_cases` for the case where that was not true and the fixture
        # became unreadable from Go.
        path.write_text(json.dumps(cases, indent=2, sort_keys=True) + "\n")
        print(f"  {len(cases):>2} cases -> {path}")

    print("\n  These are a RECORDING of the Python implementations, not a")
    print("  specification of them. If a case changes, review the diff: a")
    print("  fixture that moves silently is a parity test re-pointed at the")
    print("  new behaviour rather than one that caught the change.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
